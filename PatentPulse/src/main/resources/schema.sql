CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'RESEARCHER', active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_role CHECK (role IN ('RESEARCHER','REVIEWER','ADMIN'))
);
CREATE TABLE IF NOT EXISTS blueprints (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, owner_id BIGINT NOT NULL,
 title VARCHAR(180) NOT NULL, field VARCHAR(80) NOT NULL, summary TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (owner_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS document_versions (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, blueprint_id BIGINT NOT NULL,
 version_number INT NOT NULL, title VARCHAR(180) NOT NULL, field VARCHAR(80) NOT NULL,
 summary TEXT NOT NULL, original_name VARCHAR(255) NOT NULL, stored_name VARCHAR(80) NOT NULL UNIQUE,
 sha256 CHAR(64) NOT NULL, size_bytes BIGINT NOT NULL,
 submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, status VARCHAR(30) NOT NULL DEFAULT 'SUBMITTED',
 UNIQUE(blueprint_id,version_number), FOREIGN KEY (blueprint_id) REFERENCES blueprints(id),
 CONSTRAINT ck_status CHECK (status IN ('SUBMITTED','IN_REVIEW','INTERNALLY_REVIEWED','NEEDS_REVISION'))
);
CREATE TABLE IF NOT EXISTS review_assignments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, version_id BIGINT NOT NULL, reviewer_id BIGINT NOT NULL,
 assigned_by BIGINT NOT NULL, assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(version_id,reviewer_id), FOREIGN KEY (version_id) REFERENCES document_versions(id),
 FOREIGN KEY (reviewer_id) REFERENCES users(id), FOREIGN KEY (assigned_by) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS review_votes (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, assignment_id BIGINT NOT NULL UNIQUE,
 decision VARCHAR(10) NOT NULL, comments TEXT NOT NULL, voted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (assignment_id) REFERENCES review_assignments(id), CONSTRAINT ck_decision CHECK (decision IN ('APPROVE','REJECT'))
);
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, actor_id BIGINT, action VARCHAR(60) NOT NULL,
 target_type VARCHAR(30) NOT NULL, target_id BIGINT, details VARCHAR(500) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (actor_id) REFERENCES users(id)
);
